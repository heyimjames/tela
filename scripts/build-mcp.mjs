/**
 * Build the MCP server into ordinary compiled JavaScript.
 *
 * The output is a plain ESM file that `node` runs directly. No tsx, no ts-node,
 * no npx, and no TypeScript at runtime — the launch commands in both host
 * manifests are `node ./bin/tela-mcp.mjs`, and that has to work on a machine
 * with nothing installed but Node and this payload's dependencies.
 *
 * Bundling rather than `tsc` emit is deliberate: the shared `src/tela/*` and
 * `src/brand/*` modules are written for the Vite app, with `@/` aliases and
 * extensionless relative imports. `tsc` does not rewrite either, so its output
 * would not resolve under Node's ESM loader. esbuild resolves both at build
 * time and is a build-time tool only.
 *
 * Runtime dependencies stay external so they are loaded from `node_modules` at
 * their pinned versions and can be audited and patched independently, rather
 * than being frozen into this artifact.
 */

import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { readFile } from 'node:fs/promises'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const EXTERNAL = ['playwright', '@modelcontextprotocol/server', '@modelcontextprotocol/server/stdio', '@modelcontextprotocol/core', 'zod', 'zod/v4']

const packageJson = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))

/**
 * The source commit, injected rather than written into the source tree.
 *
 * Only the release build sets `TELA_SOURCE_COMMIT`; an ordinary build defines
 * nothing and `src/tela/producer.ts` falls back to the all-zero development
 * constant, so plain builds stay byte-identical to what they were.
 */
const sourceCommit = process.env.TELA_SOURCE_COMMIT?.trim().toLowerCase()
if (sourceCommit !== undefined && !/^[0-9a-f]{40}$/.test(sourceCommit)) {
  throw new Error(`TELA_SOURCE_COMMIT must be a 40-character lowercase hex sha, got "${process.env.TELA_SOURCE_COMMIT}"`)
}

const result = await build({
  entryPoints: [resolve(root, 'src/mcp/serve.ts')],
  outfile: resolve(root, 'dist/mcp/tela-mcp.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  sourcemap: true,
  // Node's own builtins are external by default on this platform; the list above
  // covers the pinned third-party runtime dependencies.
  external: EXTERNAL,
  alias: { '@': resolve(root, 'src') },
  define: sourceCommit ? { __TELA_SOURCE_COMMIT__: JSON.stringify(sourceCommit) } : {},
  banner: {
    js: `// ${packageJson.name} MCP server — generated by scripts/build-mcp.mjs. Do not edit.`,
  },
  logLevel: 'info',
  metafile: true,
})

const bytes = Object.values(result.metafile.outputs).reduce((sum, output) => sum + output.bytes, 0)
process.stdout.write(`MCP server built: dist/mcp/tela-mcp.mjs (${bytes} bytes)\n`)
