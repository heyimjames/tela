#!/usr/bin/env node
/**
 * Record the committed payload baseline (CLI-520).
 *
 * Run once, against a release artifact built from the pre-Milestone-2 commit, to
 * produce `tests/baselines/mcp-payload-<short>.json`. Committing the record is
 * what makes the non-interference check runnable in CI on every pull request:
 * without it, every run would have to `npm ci` and rebuild a months-old commit
 * on both operating systems to learn something that never changes.
 *
 * The record holds, per file, the sha256 of its bytes; for the four
 * commit-stamped files it additionally holds the byte length, the exact offsets
 * where the baseline commit appeared, and the sha256 of the file with only those
 * ranges blanked. Those three together are what let the checker mask the stamp
 * without being able to mask anything else.
 *
 * Usage:
 *   node scripts/record-payload-baseline.mjs <baseline-artifact-dir> --out <file>
 */

import { readFile, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'

import { METADATA_PATHS, STAMPED_PATHS, describeStamped, hashTree, sha256 } from './lib/payload-noninterference.mjs'

const argv = process.argv.slice(2)
const artifactDir = resolve(argv[0] ?? '')
const outIndex = argv.indexOf('--out')
if (!argv[0] || outIndex === -1) throw new Error('usage: record-payload-baseline.mjs <baseline-artifact-dir> --out <file>')
const outPath = resolve(argv[outIndex + 1])

const provenance = JSON.parse(await readFile(join(artifactDir, 'provenance.json'), 'utf8'))
const commit = provenance.source?.commit ?? provenance.source_commit ?? provenance.sourceCommit
if (!/^[0-9a-f]{40}$/.test(commit ?? '')) throw new Error('the baseline artifact records no usable source commit')

const files = Object.fromEntries([...(await hashTree(artifactDir))].sort())
if (Object.keys(files).length === 0) throw new Error('the baseline artifact is empty')

const stamped = {}
for (const path of STAMPED_PATHS) {
  const bytes = await readFile(join(artifactDir, path))
  stamped[path] = describeStamped(bytes, commit, sha256)
}

const metadata = {}
for (const path of METADATA_PATHS) metadata[path] = JSON.parse(await readFile(join(artifactDir, path), 'utf8'))

await writeFile(
  outPath,
  JSON.stringify(
    {
      $comment:
        'Payload baseline for the CLI-520 non-interference proof. Generated by scripts/record-payload-baseline.mjs from a release artifact built at baseline_commit. Do not hand-edit: the stamped entries pin byte offsets that only the generator can compute correctly.',
      baseline_commit: commit,
      recorded_from: {
        artifact_manifest_sha256: sha256(await readFile(join(artifactDir, 'SHA256SUMS'))),
        file_count: Object.keys(files).length,
      },
      stamped,
      metadata,
      files,
    },
    null,
    2,
  ) + '\n',
  'utf8',
)

process.stderr.write(`recorded ${Object.keys(files).length} files from ${commit} into ${outPath}\n`)
